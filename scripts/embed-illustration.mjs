/**
 * Bakes assets/hand-graphic.png into src/hand-graphic.js as a data URI.
 *
 * The library ships as a single file with no external requests, so the artwork
 * has to travel inside the bundle. The bytes are copied verbatim — base64 is an
 * encoding, not a compression, so what renders is exactly the source file.
 *
 * Do not add a quantization or resampling step here. The artwork's soft grey
 * gradients band badly under a reduced palette, which reads as pixelation at
 * card size however good the side-by-side looks at full resolution.
 *
 *   node scripts/embed-illustration.mjs
 */
import { readFile, writeFile, stat } from 'node:fs/promises';

const ROOT = new URL('..', import.meta.url);
const SOURCE = new URL('assets/hand-graphic.png', ROOT);
const TARGET = new URL('src/hand-graphic.js', ROOT);

const bytes = await readFile(SOURCE);

// Dimensions straight out of the PNG header, so the doc comment cannot drift.
const width = bytes.readUInt32BE(16);
const height = bytes.readUInt32BE(20);

await writeFile(
  TARGET,
  `/**\n` +
    ` * The hand illustration on the pre-enabled card, inlined so the library stays\n` +
    ` * a single file with no external requests.\n` +
    ` *\n` +
    ` * Byte-for-byte assets/hand-graphic.png (${width}x${height}). Generated by\n` +
    ` * scripts/embed-illustration.mjs — do not edit by hand.\n` +
    ` */\n` +
    `export const HAND_GRAPHIC =\n` +
    `  'data:image/png;base64,${bytes.toString('base64')}';\n`,
);

const out = await stat(TARGET);
console.log(
  `hand-graphic.png ${bytes.length.toLocaleString()}B (${width}x${height}) -> ` +
    `hand-graphic.js ${out.size.toLocaleString()}B`,
);
